<?php

use App\Controllers\Web\Contact;
use CodeIgniter\Controller;
use CodeIgniter\Router\RouteCollection;
use App\Controllers\Admin;
use App\Controllers\Web;

$routes->set404Override('\App\Controllers\Web\Page::show404');

/** @var RouteCollection $routes */
// $routes->get('/',[Web\Page::class, 'index']);
$routes->get('under_construction',[Web\Page::class, 'under_construction']);

// Protected Admin CMS Routes
$routes->group('admin', ['namespace' => 'App\Controllers\Admin'], function($routes) {
    // Sheild routes for authentication and authorization
    service('auth')->routes($routes);
    $routes->get('welcome','\App\Controllers\Home::index');
    $routes->get('dashboard', 'Dashboard::index');
    $routes->presenter('pages');
    $routes->presenter('templates');
    $routes->presenter('projects');
    $routes->presenter('project_images', ['controller' => '\App\Controllers\Admin\ProjectImages']);
    $routes->presenter('uploaded_images', ['controller' => '\App\Controllers\Admin\UploadedImages']);
    $routes->post('upload', 'UploadedImages::uploadImages');
    $routes->post('delete_image/(:num)',[[Admin\UploadedImages::class, 'deleteImage'], '$1']);
    $routes->get('api/images', 'ProjectImages::getImagesHtml');
    $routes->presenter('service_plugins', ['controller' => '\App\Controllers\Admin\ServicePlugins']);
    $routes->presenter('users');
    $routes->group('settings', function($routes){
        $routes->get('', 'Settings::index');
        $routes->put('save', 'Settings::update');
    });
});

// Public Web Routes
$routes->group('/', ['filter' => ['adminAuth']], function($routes) {
    $routes->get('',[Web\Page::class, 'index']);
    // Contact Page Route
    $routes->get('contact',[Web\Contact::class, 'contact']);
    // Consultation
    $routes->get('consultation',[Web\Contact::class, 'consultation']);
    // Projects Articles
    $routes->get('projects', [Web\Project::class, 'index']);
    // Project Article Post
    $routes->get('project/(:segment)', [Web\Project::class, 'show']);
    // Dynamic catch-all for custom pages generated by the CMS
    $routes->get('(:any)',[[Web\Page::class, 'render'], '$1']);
    //Contact Message
    $routes->post('contact',[Web\Contact::class, 'sendMessage']);
    // Consultation Message
    $routes->post('consultation',[Web\Contact::class, 'consultationRequest']);
});